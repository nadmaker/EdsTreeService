const PHONE_HREF      = CLIENT.contact.phoneTel;
const PHONE_DISPLAY   = CLIENT.contact.phoneDisplay;
/* EMERGENCY_PHONE was here, reading CLIENT.contact.emergencyPhoneDisplay.
   Removed 2026-09-01 with its only consumer (see the emergency-block note
   further down). It resolved to an EMPTY STRING for EBS, which is what made
   the sentence it fed end in a dangling "or ." — worth keeping in the record,
   because an empty config value that renders as a typo is a failure mode
   nothing warns about. Restore both together if EBS ever gets an
   after-hours line. */
const EMAIL_HREF      = CLIENT.contact.emailHref;
const EMAIL_DISPLAY   = CLIENT.contact.email;

type ApiOk = { ok: true; accepted: true; confirmationSent?: boolean };
type ApiErr = {
  ok: false;
  error: { code: string; message: string; field?: string; reason?: string };
};

/* ── Service Type options ─────────────────────────────────────────────
   ⚠️ THIS LIST IS SENT TO THE CUSTOMER-FACING LEAD EMAIL. The selection POSTs
   to /api/contact as `service_type` and is rendered verbatim into the email
   body, so a wrong entry is not cosmetic. Until 2026-09-01 this dropdown
   offered "Tree Service", "Tree Care & Trimming", "Stump Grinding" and
   "Landscape & Shrub Care" — the previous client's services — so a roofing
   enquiry from /contact arrived reading "Service: Stump Grinding".

   THIS WAS THE LAST OF THE THREE. The same defect was fixed on the city
   landings (commit 433fab0) and on the home form earlier the same day. It
   survived both passes because the options live inside a Radix PORTAL and so
   never appear in the served HTML — a crawl-based audit reports this file
   clean, which is exactly how the other two were found only by reading source.

   MIRRORS the approved list on the other two surfaces: five services plus
   "Other". Ryan trimmed Gutter Installation and Gutter Cleaning on 2026-09-01;
   gutter work arrives as "Other" and both services keep their own pages.

   ⚠️ NOT imported from servicePageData — no file in sections/ imports from
   pages/ (root §13.3.7). Add a service in all three places.

   `key` is the tracking slug and matches servicePageData[*].slug, so the
   select_service label is the DECLARED slug rather than a slugified display
   name — root §8.5's failure mode, where punctuation in a display name
   silently breaks the analytics join. */
const SERVICE_OPTIONS: ReadonlyArray<{ key: string; label: string }> = [
  { key: "roof-replacement", label: "Roof Replacement" },
  { key: "roof-repair", label: "Roof Repair" },
  { key: "roof-installation", label: "Roof Installation" },
  { key: "metal-roof-installation", label: "Metal Roof Installation" },
  { key: "siding-installation", label: "Siding Installation" },
  /* Last on purpose: a catch-all above real options invites people to stop
     reading. "other" is not a service slug and has no /services/ route. */
  { key: "other", label: "Other" },
];

export interface ContactInfoFormWrapperProps {
  id?: string;
  className?: string;

  /** Content overrides */
  title?: React.ReactNode;
  description?: React.ReactNode;

  /** Form config */
  formId?: string;
  formName?: string;
  siteKey?: string;

  /** Tracking context */
  trackingSection?: string;
  trackingCity?: string;
  trackingService?: string;
  trackingPageType?: string;
}

export default function ContactInfoFormWrapper({
  id = "contact-info-form",
  className,
  title = "Contact Our Team",
  /* ⚠️ EBS-Contact passes no content props, so this default IS the live
     copy. Closed on "…taking great care of you and your trees" until
     2026-09-01. */
  description = "Use the form to tell us more about your project or ask us a question, and we'll be in touch as soon as possible. Or, if you prefer, give us a call or send an email. We look forward to talking with you about your roof, siding or gutters.",
  formId = "contact-page-form",
  formName = "Contact Page Estimate",
  siteKey = CLIENT.siteKey,
  trackingSection = "contact-info-form",
  trackingCity,
  trackingService = CLIENT.service.trackingSlug,
  trackingPageType = "contact",
}: ContactInfoFormWrapperProps) {
  const sectionRef = useRef<HTMLElement | null>(null);
  const hasStartedRef = useRef(false);
  const hasSubmittedRef = useRef(false);
  const hasTrackedSectionRef = useRef(false);
  const startedAtMsRef = useRef<number | null>(null);

  // Form fields
  const [firstName, setFirstName] = useState("");
  const [lastName, setLastName] = useState("");
  const [address, setAddress] = useState("");
  const [propertyType, setPropertyType] = useState("residential");
  const [email, setEmail] = useState("");
  const [phone, setPhone] = useState("");
  const [serviceType, setServiceType] = useState("");
  const [message, setMessage] = useState("");

  // Honeypot
  const [company, setCompany] = useState("");

  // UI state
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [status, setStatus] = useState<"idle" | "success" | "error">("idle");
  const [errorMsg, setErrorMsg] = useState("");

  const pushToDataLayer = (payload: Record<string, unknown>) => {
    if (typeof window === "undefined") return;

    (
      window as Window & { dataLayer?: Record<string, unknown>[] }
    ).dataLayer = (
      window as Window & { dataLayer?: Record<string, unknown>[] }
    ).dataLayer || [];

    (
      window as Window & { dataLayer?: Record<string, unknown>[] }
    ).dataLayer?.push(payload);
  };

  /* Takes the DECLARED slug from SERVICE_OPTIONS, not the display name. This
     used to slugify the label at call time — root §8.5's documented failure
     mode, where punctuation or a double space in a display name silently
     yields a slug that no longer joins to servicePageData[*].slug, so a
     marketing copy edit moves a GA4 dimension with nothing in the diff to
     show it. Same fix already applied to the other two forms. */
  const pushServiceSelection = (serviceSlug: string) => {
    pushToDataLayer({
      event: "select_service",
      label: `contact-info-form-service-${serviceSlug}`,
      section: trackingSection,
      city: trackingCity,
      service: trackingService,
      page_type: trackingPageType,
    });
  };

  const previewPayload = useMemo(
    () => ({
      site: siteKey,
      name: `${firstName.trim()} ${lastName.trim()}`.trim(),
      phone: phone.trim(),
      email: email.trim(),
      address: address.trim(),
      property_type: propertyType,
      service_type: serviceType || "(not_selected)",
      message: message.trim(),
      company: company.trim(),
      started_at_ms: startedAtMsRef.current ?? undefined,
    }),
    [siteKey, firstName, lastName, phone, email, address, propertyType, serviceType, message, company]
  );

  // Section visibility tracking
  useEffect(() => {
    const node = sectionRef.current;
    if (!node) return;

    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          if (hasTrackedSectionRef.current) return;

          hasTrackedSectionRef.current = true;

          pushToDataLayer({
            event: "view_section",
            section: trackingSection,
            city: trackingCity,
            service: trackingService,
            page_type: trackingPageType,
          });

          observer.unobserve(entry.target);
        });
      },
      { threshold: 0.4 }
    );

    observer.observe(node);

    return () => observer.disconnect();
  }, [trackingSection, trackingCity, trackingService, trackingPageType]);

  // Form start tracking
  useEffect(() => {
    if (typeof window === "undefined") return;

    const root = document.getElementById(id);
    if (!root) return;

    const form = root.querySelector("form");
    if (!form) return;

    const onFocusIn = () => {
      if (!startedAtMsRef.current) startedAtMsRef.current = Date.now();

      if (hasStartedRef.current) return;
      hasStartedRef.current = true;

      pushToDataLayer({
        event: "form_start",
        form_id: formId,
        form_name: formName,
        section: trackingSection,
        city: trackingCity,
        service: trackingService,
        page_type: trackingPageType,
      });
    };

    form.addEventListener("focusin", onFocusIn);
    return () => form.removeEventListener("focusin", onFocusIn);
  }, [id, formId, formName, trackingSection, trackingCity, trackingService, trackingPageType]);

  const pushSubmitAttempt = () => {
    if (hasSubmittedRef.current) return;
    hasSubmittedRef.current = true;

    pushToDataLayer({
      event: "form_submit_attempt",
      form_id: formId,
      form_name: formName,
      section: trackingSection,
      city: trackingCity,
      service: trackingService,
      page_type: trackingPageType,
      service_type: serviceType || "(not_selected)",
    });
  };

  const clientErrors = useMemo(() => {
    const errs: string[] = [];
    if (!firstName.trim()) errs.push("First name is required.");
    if (!lastName.trim()) errs.push("Last name is required.");
    if (!phone.trim()) errs.push("Phone is required.");
    if (!email.trim()) errs.push("Email is required.");
    return errs;
  }, [firstName, lastName, phone, email]);

  const resetFormFields = () => {
    setFirstName("");
    setLastName("");
    setAddress("");
    setPropertyType("residential");
    setEmail("");
    setPhone("");
    setServiceType("");
    setMessage("");
    setCompany("");
    startedAtMsRef.current = null;
  };

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();

    setStatus("idle");
    setErrorMsg("");

    pushSubmitAttempt();

    // Honeypot
    if (company.trim()) {
      setStatus("success");
      resetFormFields();
      return;
    }

    if (clientErrors.length) {
      setStatus("error");
      setErrorMsg(clientErrors[0] ?? "Please check your form fields.");

      pushToDataLayer({
        event: "form_submit_error",
        form_id: formId,
        form_name: formName,
        section: trackingSection,
        city: trackingCity,
        service: trackingService,
        page_type: trackingPageType,
        service_type: serviceType || "(not_selected)",
        reason: "client_validation",
      });

      return;
    }

    if (!startedAtMsRef.current) startedAtMsRef.current = Date.now() - 3000;

    setIsSubmitting(true);

    try {
      const res = await fetch("/api/contact", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(previewPayload),
      });

      const data = (await res.json().catch(() => null)) as ApiOk | ApiErr | null;

      if (!res.ok || !data || (data as any).ok !== true) {
        const reason =
          (data as any)?.error?.code ||
          (data as any)?.error?.reason ||
          (data as any)?.error?.message ||
          `http_${res.status}`;

        pushToDataLayer({
          event: "form_submit_error",
          form_id: formId,
          form_name: formName,
          section: trackingSection,
          city: trackingCity,
          service: trackingService,
          page_type: trackingPageType,
          service_type: serviceType || "(not_selected)",
          reason,
        });

        throw new Error(
          (data as any)?.error?.message || "Something went wrong. Please try again."
        );
      }

      pushToDataLayer({
        event: "form_submit_success",
        form_id: formId,
        form_name: formName,
        section: trackingSection,
        city: trackingCity,
        service: trackingService,
        page_type: trackingPageType,
        service_type: serviceType || "(not_selected)",
      });

      pushToDataLayer({
        event: "generate_lead",
        form_id: formId,
        form_name: formName,
        section: trackingSection,
        city: trackingCity,
        service: trackingService,
        page_type: trackingPageType,
        value: 1,
        currency: "USD",
        service_type: serviceType || "(not_selected)",
      });

      setStatus("success");
      resetFormFields();

      hasStartedRef.current = false;
      hasSubmittedRef.current = false;
    } catch (err: any) {
      setStatus("error");
      setErrorMsg(err?.message || "Something went wrong. Please try again.");
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <section
      id={id}
      ref={sectionRef}
      className={["w-full overflow-x-hidden", className]
        .filter(Boolean)
        .join(" ")}
      data-section={trackingSection}
      data-city={trackingCity}
      data-service={trackingService}
      data-page-type={trackingPageType}
    >
      <Infoand_ContactForm
  className="
    w-full mx-auto
    max-md:px-6 max-md:py-10
    max-md:[&>div]:flex-col
    max-md:[&>div]:gap-10
    max-md:[&>div>div:last-child]:w-full
  "
        title={title}
        description={description}
        phoneLabel={<strong>Phone</strong>}
        phoneNumber={
          <a
            href={PHONE_HREF}
            className="underline underline-offset-2 hover:opacity-80"
            data-event="click_call"
            data-label="contact-info-phone"
            data-section={trackingSection}
            data-city={trackingCity}
            data-service={trackingService}
            data-page-type={trackingPageType}
          >
            {PHONE_DISPLAY}
          </a>
        }
        emailLabel={<strong>Email</strong>}
        emailAddress={
          <a
            href={EMAIL_HREF}
            className="underline underline-offset-2 hover:opacity-80"
            data-event="click_email"
            data-label="contact-info-email"
            data-section={trackingSection}
            data-city={trackingCity}
            data-service={trackingService}
            data-page-type={trackingPageType}
          >
            {EMAIL_DISPLAY}
          </a>
        }
        officeHoursLabel={<strong>Office Hours</strong>}
        officeHours="Mon-Fri 7am to 5pm ET (Excluding holidays)"
        /* ⚠️ EMERGENCY BLOCK REMOVED 2026-09-01, deliberately NOT reworded.
           It read `emergencyLabel="Need emergency service?"` over "If you have
           a TREE EMERGENCY, please submit a Message to our Phone Or Call
           {PHONE_DISPLAY} or {EMERGENCY_PHONE}" — MUST-NOT-SHIP on the CLAIMS
           REGISTER twice over: the emergency framing itself, and the previous
           client's vocabulary. Same treatment the footer's "Available 24/7"
           row and the stats band's 24/7 tile received: REMOVED, because EBS
           has no emergency line and no rewording makes an availability promise
           shippable without one. A first pass here reworded it; that was the
           wrong call and is why this note exists.

           ⚠️ IT WAS ALSO VISIBLY BROKEN, which nothing reported. The sentence
           ended "Call {PHONE_DISPLAY} or {EMERGENCY_PHONE}", and
           EMERGENCY_PHONE reads CLIENT.contact.emergencyPhoneDisplay —
           deliberately an EMPTY STRING for EBS. So /contact shipped a sentence
           ending "or ." with nothing after the "or". An empty template token
           throws no error; it just renders as a typo.

           Infoand_ContactForm renders both slots as `{prop ? … : null}`, so
           omitting them leaves no empty heading and no stray box — verified in
           the component rather than assumed. If EBS ever gets a real
           after-hours line, populate emergencyPhoneDisplay in client.config.ts
           and restore both props together. */
        form={
          <div className="flex w-full flex-col gap-2 rounded-lg bg-white p-8 shadow-lg">
            <span className="text-heading-3 font-heading-3 text-default-font mb-4">
              Contact us
            </span>

            {status === "success" ? (
              <div className="w-full rounded-lg border border-green-200 bg-green-50 px-4 py-3 text-sm text-green-900 mb-2">
                Thanks — we got your request. We'll reach out shortly.
              </div>
            ) : null}

            {status === "error" ? (
              <div className="w-full rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-900 mb-2">
                {errorMsg || "Please check the form and try again."}
              </div>
            ) : null}

            <form onSubmit={handleSubmit} className="flex w-full flex-col gap-4">
              {/* Honeypot */}
              <div className="hidden">
                <label>
                  Company
                  <input
                    value={company}
                    onChange={(e) => setCompany(e.target.value)}
                    autoComplete="off"
                    tabIndex={-1}
                  />
                </label>
              </div>

              <div className="flex w-full gap-4 max-md:flex-col">
                <TextField variant="outline" label="First Name *" icon={<FeatherUser />} className="flex-1">
                  <TextField.Input
                    placeholder=""
                    value={firstName}
                    onChange={(e: any) => setFirstName(e.target.value)}
                    autoComplete="given-name"
                  />
                </TextField>
                <TextField variant="outline" label="Last Name *" icon={<FeatherUser />} className="flex-1">
                  <TextField.Input
                    placeholder=""
                    value={lastName}
                    onChange={(e: any) => setLastName(e.target.value)}
                    autoComplete="family-name"
                  />
                </TextField>
              </div>

              <TextField variant="outline" label="Full Property Address" icon={<FeatherMapPin />}>
                <TextField.Input
                  placeholder="Start typing your address..."
                  value={address}
                  onChange={(e: any) => setAddress(e.target.value)}
                  autoComplete="street-address"
                />
              </TextField>

              <div className="flex flex-col gap-1">
                <span className="text-caption font-caption text-default-font">
                  Property Type *
                </span>
                <div className="flex items-center gap-4">
                  <label className="flex items-center gap-2 text-sm">
                    <input
                      type="radio"
                      name="propertyType"
                      value="residential"
                      checked={propertyType === "residential"}
                      onChange={() => setPropertyType("residential")}
                      className="accent-brand-primary"
                    />
                    Residential
                  </label>
                  <label className="flex items-center gap-2 text-sm">
                    <input
                      type="radio"
                      name="propertyType"
                      value="commercial"
                      checked={propertyType === "commercial"}
                      onChange={() => setPropertyType("commercial")}
                      className="accent-brand-primary"
                    />
                    Commercial
                  </label>
                </div>
              </div>

              <TextField variant="outline" label="Email Address *" icon={<FeatherMail />}>
                <TextField.Input
                  placeholder=""
                  value={email}
                  onChange={(e: any) => setEmail(e.target.value)}
                  inputMode="email"
                  autoComplete="email"
                />
              </TextField>

              <TextField variant="outline" label="Phone *" icon={<FeatherPhone />}>
                <TextField.Input
                  placeholder=""
                  value={phone}
                  onChange={(e: any) => setPhone(e.target.value)}
                  inputMode="tel"
                  autoComplete="tel"
                />
              </TextField>

              <SubframeCore.DropdownMenu.Root>
                <SubframeCore.DropdownMenu.Trigger asChild={true}>
                  <TextField variant="outline" label="Service Type" icon={<FeatherList />}>
                    <TextField.Input placeholder="" value={serviceType} readOnly />
                  </TextField>
                </SubframeCore.DropdownMenu.Trigger>

                <SubframeCore.DropdownMenu.Portal>
                  <SubframeCore.DropdownMenu.Content
                    side="bottom"
                    align="start"
                    sideOffset={4}
                    asChild={true}
                  >
                    <DropdownMenu className="min-w-[240px]">
                      {/* ⚠️ DropdownItem accepts an `icon` prop and NEVER
                          RENDERS IT — it destructures `icon` (defaulting to
                          <FeatherStar />) and returns only `children`. The four
                          Feather icons passed here until 2026-09-01 were dead
                          props drawing nothing, which is also why removing them
                          changes no pixels. Glyphs go through `children`, a real
                          slot (root §7.1 rung 1), rather than through the prop
                          that looks like the right one.

                          Same SERVICE_ICONS map the services grid, the landing
                          form and the home form use, so all four surfaces cannot
                          drift on what a service looks like. */}
                      {SERVICE_OPTIONS.map(({ key, label }) => {
                        const Glyph = SERVICE_ICONS[key];
                        return (
                          <DropdownMenu.DropdownItem
                            key={key}
                            onClick={() => {
                              setServiceType(label);
                              pushServiceSelection(key);
                            }}
                          >
                            <span className="flex items-center gap-2">
                              {Glyph ? (
                                <Glyph className="h-4 w-4 flex-none text-brand-primary" />
                              ) : null}
                              {label}
                            </span>
                          </DropdownMenu.DropdownItem>
                        );
                      })}
                    </DropdownMenu>
                  </SubframeCore.DropdownMenu.Content>
                </SubframeCore.DropdownMenu.Portal>
              </SubframeCore.DropdownMenu.Root>

              <TextArea variant="outline" label="Messages and Questions" helpText="">
                <TextArea.Input
                  placeholder=""
                  value={message}
                  onChange={(e: any) => setMessage(e.target.value)}
                />
              </TextArea>

              <Button
                type="submit"
                variant="brand-primary"
                size="large"
                disabled={isSubmitting}
                className="
                  w-full h-12
                  !text-white
                  [&_*]:!text-white
                  disabled:opacity-60
                "
              >
                {isSubmitting ? "Submitting..." : "Submit"}
              </Button>
            </form>
          </div>
        }
      />
    </section>
  );
}
